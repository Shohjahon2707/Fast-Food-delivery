class Command(BaseCommand):
    help = "Add six clearly marked demo restaurants without overwriting existing data or users."

    @transaction.atomic
    def handle(self, *args, **options):
        restaurants = []
        for name, cuisine, description, cover, minutes, address in RESTAURANTS:
            restaurant, _ = Restaurant.objects.get_or_create(
                name=name,
                is_demo=True,
                defaults={
                    "cuisine": cuisine,
                    "description": description,
                    "cover": cover,
                    "delivery_minutes": minutes,
                    "address": address,
                    "latitude": "41.311081",
                    "longitude": "69.240562",
                },
            )
            restaurants.append(restaurant)
        added = 0
        for index, category_name, name, price, weight, image, veg, description in DISHES:
            category, _ = Category.objects.get_or_create(name=category_name)
            role = {
                "Салаты": "side", "Закуски": "side", "Гарниры": "side",
                "Напитки": "drink", "Десерты": "dessert",
            }.get(category_name, "main")
            item, created = MenuItem.objects.get_or_create(
                restaurant=restaurants[index],
                name=name,
                defaults={
                    "category": category,
                    "price": price,
                    "weight": weight,
                    "seed_image": "food/" + image,
                    "is_vegetarian": veg,
                    "description": description,
                    "lunch_role": role,
                },
            )
            if not item.lunch_role:
                item.lunch_role = role
                item.save(update_fields=["lunch_role"])
            added += created
        self.stdout.write(
            self.style.SUCCESS(
                f"Demo restaurants: 6; new dishes: {added}. Existing data preserved."
            )
        )
